// ── Helper: smooth opacity fade based on zoom ─────────────────────────────────
export function getBorderOpacity(zoom: number, minZoom: number, fadeRange = 0.25): number {
  if (zoom < minZoom) return 0;
  if (zoom > minZoom + fadeRange) return 1;
  return (zoom - minZoom) / fadeRange;
}

// ── Helper: camera z → zoom level (1.0 = fully zoomed out, 4.0 = max in) ─────
export function cameraZToZoom(cameraZ: number): number {
  // camera.position.z ranges 1.6 → 5.0; we map that to ~3.1 → 1.0
  return Math.max(1.0, Math.min(4.0, 5.0 / cameraZ));
}
